/**
 * Школьные каникулы в Москве: осенние, зимние, весенние и летние. Окна приблизительные — точные даты
 * каждый год утверждает департамент образования, а для «уместно ли сегодня» хватает недели-другой.
 */
export function isSchoolBreak(month: number, day: number): boolean {
  const md = month * 100 + day;
  return (md >= 1026 && md <= 1104) || md >= 1227 || md <= 111 || (md >= 321 && md <= 331) || (md >= 601 && md <= 831);
}

