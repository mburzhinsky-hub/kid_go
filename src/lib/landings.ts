const bySlug = new Map(LANDINGS.map((l) => [l.slug, l]));
export const landingBySlug = (slug: string) => bySlug.get(slug);

/** Места подборки: по уместности, с ограничением на категорию; между равными — сначала с проверенными данными, потом по названию. */
export function landingPlaces(l: Landing): Place[] {
  const ranked = places
    .filter((p) => !p.slug.startsWith("osm-"))
    .map((p) => ({ p, s: l.fit(p) }))
    .filter((x): x is { p: Place; s: number } => x.s != null)
    .sort((a, b) => b.s - a.s || a.p.title.localeCompare(b.p.title, "ru"));
  const taken = new Map<CategoryId, number>();
  const out: Place[] = [];
  for (const { p } of ranked) {
    const cap = l.perCategory?.[p.category];
    const n = taken.get(p.category) ?? 0;
    if (cap != null && n >= cap) continue;
    taken.set(p.category, n + 1);
    out.push(p);
    if (out.length >= l.limit) break;
  }
  return out;
}

const cache = new Map<string, Place[]>();
export function placesOfLanding(l: Landing): Place[] {
  let v = cache.get(l.slug);
  if (!v) cache.set(l.slug, (v = landingPlaces(l)));
  return v;
}

/** Подборки, у которых достаточно мест, чтобы их публиковать. */
export const publishedLandings = (): Landing[] => LANDINGS.filter((l) => placesOfLanding(l).length >= l.min);

/** В каких опубликованных подборках есть место (для ссылок со страницы места). */
export function landingsOfPlace(slug: string): Landing[] {
  return publishedLandings().filter((l) => placesOfLanding(l).some((p) => p.slug === slug));
}

