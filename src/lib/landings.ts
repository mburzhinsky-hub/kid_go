const DAYS = ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"];

/** Режим одной строкой — только когда он одинаков во все рабочие дни; иначе null (подробности в карточке места). */
export function hoursLine(h: OpeningHours): string | null {
  const open = h.map((x, i) => (x ? i : -1)).filter((i) => i >= 0);
  if (!open.length) return null;
  const first = h[open[0]]!;
  if (!open.every((i) => h[i]![0] === first[0] && h[i]![1] === first[1])) return null;
  const time = first[0] === "00:00" && first[1] === "24:00" ? "круглосуточно" : `${first[0]}–${first[1]}`;
  if (open.length === 7) return `ежедневно ${time}`;
  const contiguous = open.every((v, i) => i === 0 || v === open[i - 1] + 1);
  if (contiguous) return `${DAYS[open[0]]}–${DAYS[open[open.length - 1]]} ${time}`;
  const closed = DAYS.filter((_, i) => !h[i]);
  return `ежедневно ${time}, кроме ${closed.map((d) => d.toLowerCase()).join(", ")}`;
}

/** Подтверждённые факты места для строки списка: цена и режим показываются только если они сверены с официальным сайтом. */
export function verifiedFacts(p: Place): { price?: string; hours?: string; hoursByDay?: boolean } {
  const out: { price?: string; hours?: string; hoursByDay?: boolean } = {};
  if (verifiedField(p, "price")) out.price = p.price_max === 0 ? "вход бесплатный" : p.price_min === 0 ? `вход до ${formatPrice(p.price_max)}` : `вход от ${formatPrice(p.price_min)}`;
  if (verifiedField(p, "opening_hours")) {
    const line = hoursLine(p.opening_hours);
    if (line) out.hours = line;
    else out.hoursByDay = true;
  }
  return out;
}
