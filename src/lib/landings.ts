/**
 * Посадочные подборки под реальные поисковые запросы («куда сходить с ребёнком 3 лет в Москве», «…в дождь»).
 * Страницы собираются из каталога по явным правилам: никакого ручного списка, который устареет.
 * Факты (цена, часы) на страницах — только подтверждённые на официальном сайте; остальное отправляет в карточку места.
 */

export interface Landing {
  slug: string;
  /** Короткая подпись для ссылок и кнопок. */
  short: string;
  /** Запрос, под который написана страница (для редакторов; на сайте не показывается). */
  query: string;
  h1: string;
  /** Заголовок вкладки без « · Kids Go»: его добавляет шаблон. */
  title: string;
  description: string;
  lead: string;
  /** Как составлена подборка — одним предложением, чтобы читатель понимал правило. */
  how: string;
  tips: string[];
  /** null — место не подходит; больше число — выше в списке. */
  fit: (p: Place) => number | null;
  /** Не больше N мест одной категории: иначе подборка превращается в список парков. */
  perCategory?: Partial<Record<CategoryId, number>>;
  limit: number;
  /** Меньше мест — страницу не публикуем (не выпускаем пустышки). */
  min: number;
  related: string[];
  /** Ситуация из «Ситуаций» для кнопки «Собрать день». */
  scenario?: string;
  /** Показывать «за городом» и расстояние: подборка про поездки. */
  trip?: boolean;
}

const ATTRACTIONS: CategoryId[] = ["park", "play", "museum", "active", "animals"];
const isMsk = (p: Place) => p.region !== "mo";
const verifiedField = (p: Place, f: "price" | "opening_hours" | "address") => (p.verified_fields ?? []).includes(f);
/** Небольшая добавка за то, что часы и цены места уже сверены с официальным сайтом, и за редакторскую отметку «хит». */
const trust = (p: Place) => (verifiedField(p, "price") ? 0.6 : 0) + (verifiedField(p, "opening_hours") ? 0.6 : 0) + (p.is_hit ? 0.4 : 0);
const ageFit = (p: Place, age: number) => p.age_min <= age && p.age_max >= age;
const attraction = (p: Place) => ATTRACTIONS.includes(p.category);

